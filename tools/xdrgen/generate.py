"""Generate C++20 types and codecs from the vendored XDR AST (xdr/xdr.json).

Outputs:
  include/stellar/xdr/generated/types.hpp   all types (forward decls, typedefs,
                                          enums, structs, unions, consts)
  src/xdr/generated/codec_<file>.cpp        Codec<T> specializations per source file
  src/xdr/generated/registry.cpp            name -> type entry table

Usage:
  tools/xdrgen/generate.py            regenerate in place
  tools/xdrgen/generate.py --check    verify committed files are up to date
"""

