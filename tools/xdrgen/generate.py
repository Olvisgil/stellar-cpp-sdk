CPP_KEYWORDS = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool",
    "break", "case", "catch", "char", "char8_t", "char16_t", "char32_t", "class",
    "compl", "concept", "const", "consteval", "constexpr", "constinit", "const_cast",
    "continue", "co_await", "co_return", "co_yield", "decltype", "default", "delete",
    "do", "double", "dynamic_cast", "else", "enum", "explicit", "export", "extern",
    "false", "float", "for", "friend", "goto", "if", "inline", "int", "long",
    "mutable", "namespace", "new", "noexcept", "not", "not_eq", "nullptr", "operator",
    "or", "or_eq", "private", "protected", "public", "register", "reinterpret_cast",
    "requires", "return", "short", "signed", "sizeof", "static", "static_assert",
    "static_cast", "struct", "switch", "template", "this", "thread_local", "throw",
    "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using",
    "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq",
}


def ident(name: str) -> str:
    """Escape a C++ identifier (keywords get a trailing underscore)."""
    if name in CPP_KEYWORDS:
        return name + "_"
    return name


def camelize(screaming: str) -> str:
    """js-xdr factory naming: KEY_TYPE_ED25519 -> keyTypeEd25519."""
    parts = [p for p in screaming.split("_") if p]
    if not parts:
        return "v"
    out = parts[0].lower()
    for p in parts[1:]:
        out += p[:1].upper() + p[1:].lower()
    if out[0].isdigit():
        out = "v" + out
    return ident(out)


def pad4(n: int) -> int:
    return (n + 3) // 4 * 4


# ---------------------------------------------------------------------------
# AST model
# ---------------------------------------------------------------------------

@dataclass
class Field:
    name: str
    type: dict  # raw type node from the AST


@dataclass
class Arm:
    cases: list  # [{'name','value'}] or [{'value'}]
    name: str | None  # field name; None for void arms
    type: dict | None
    index: int = -1  # variant alternative index in emission


@dataclass
class Def:
    kind: str  # struct|union|enum|typedef|const
    name: str
    file_index: int
    source: str
    data: dict


# ---------------------------------------------------------------------------
# Generator
# ---------------------------------------------------------------------------

class Gen:
    def __init__(self, ast: dict):
        self.defs: list[Def] = [
            Def(d["kind"], d["name"], d["file_index"], d.get("source", ""), d)
            for d in ast["definitions"]
        ]
        self.by_name = {d.name: d for d in self.defs}
        self.typedefs = {d.name: d for d in self.defs if d.kind == "typedef"}
        self.structs = {d.name: d for d in self.defs if d.kind == "struct"}
        self.unions = {d.name: d for d in self.defs if d.kind == "union"}
        self.enums = {d.name: d for d in self.defs if d.kind == "enum"}

        # (parent_type, member_kind, member_index) -> 'box' | 'optional_box'
        self.boxed_edges: dict[tuple, str] = {}
        self.emit_order: list[str] = []
        self.min_size: dict[str, int] = {}
        self.min_depth: dict[str, int] = {}

        self._build_graph()
        self._compute_min_sizes()
        self._compute_min_depths()

    # ----- type resolution --------------------------------------------------

    def resolve_ref(self, name: str) -> Def | None:
        """Follow typedef aliases to the ultimate named definition."""
        seen = set()
        while name in self.typedefs and name not in seen:
            seen.add(name)
            t = self.typedefs[name].data["type"]
            if t["kind"] != "ref":
                return self.typedefs[name]
            name = t["name"]
        return self.by_name.get(name)

    def final_kind(self, name: str) -> str:
        """Kind of the resolved definition: struct/union/enum/<type-node kind>."""
        d = self.by_name.get(name)
        if d is None:
            return "unknown"
        if d.kind == "typedef":
            return self.type_kind_of(d.data["type"])
        return d.kind

    def type_kind_of(self, t: dict) -> str:
        if t["kind"] == "ref":
            return self.final_kind(t["name"])
        return t["kind"]

    # ----- C++ type mapping -------------------------------------------------

    def cpp_type(self, t: dict, edge_key: tuple | None = None) -> str:
        """Map an AST type node to a C++ type name."""
        kind = t["kind"]
        if kind == "ref":
            return ident(t["name"])
        if kind == "int":
            return "std::int32_t"
        if kind == "unsigned_int":
            return "std::uint32_t"
        if kind == "hyper":
            return "std::int64_t"
        if kind == "unsigned_hyper":
            return "std::uint64_t"
        if kind == "bool":
            return "bool"
        if kind == "opaque_fixed":
            return f"std::array<std::uint8_t, {t['size']}>"
        if kind == "opaque_var":
            mx = t.get("max_size")
            return f"BoundedBytes<{mx if mx is not None else 'kUnbounded'}>"
        if kind == "string":
            mx = t.get("max_size")
            return f"BoundedString<{mx if mx is not None else 'kUnbounded'}>"
        if kind == "var_array":
            elem = self.cpp_type(t["element"])
            mx = t.get("max_count")
            return f"BoundedVector<{elem}, {mx if mx is not None else 'kUnbounded'}>"
        if kind == "array":
            elem = self.cpp_type(t["element"])
            return f"std::array<{elem}, {t['count']}>"
        if kind == "optional":
            elem = self.cpp_type(t["element"])
            if edge_key and self.boxed_edges.get(edge_key) == "optional":
                return f"OptionalBox<{elem}>"
            return f"std::optional<{elem}>"
        raise ValueError(f"unknown type kind {kind!r}")

    def boxed_cpp_type(self, t: dict, edge_key: tuple) -> str:
        """cpp_type for a member that may sit on a cyclic edge."""
        kind = self.boxed_edges.get(edge_key)
        if kind is None:
            return self.cpp_type(t, edge_key)
        if kind == "optional":
            return f"OptionalBox<{self.cpp_type(t['element'])}>"
        if kind == "array":
            return f"std::array<Box<{self.cpp_type(t['element'])}>, {t['count']}>"
        # 'direct' and 'vec': heap-indirect the whole payload
        return f"Box<{self.cpp_type(t)}>"

    # ----- dependency graph / boxing ----------------------------------------

    def _member_edges(self, t: dict) -> list[tuple[str, str]]:
        """Named types requiring completeness inside a member: (target, edge_kind).

        edge_kind: 'direct' | 'optional' | 'array' | 'vec'.
        All named-type containment is an edge: std::variant instantiates
        alternatives eagerly enough that even vector elements must be
        complete when the containing struct is compared/destroyed.
        """
        out: list[tuple[str, str]] = []

        def element_edge(tt: dict, wrapper: str) -> None:
            et = tt["element"]
            if et["kind"] == "ref":
                d = self.by_name.get(et["name"])
                if d is not None and d.kind == "typedef":
                    walk(et, wrapper)
                    return
                if d is not None and d.kind in ("struct", "union"):
                    out.append((et["name"], wrapper))
                    return
            walk(et, wrapper)

        def walk(tt: dict, wrapper: str):
            kind = tt["kind"]
            if kind == "ref":
                d = self.by_name.get(tt["name"])
                if d is None:
                    return
                if d.kind == "typedef":
                    walk(d.data["type"], wrapper)
                elif d.kind in ("struct", "union"):
                    out.append((tt["name"], wrapper))
                return
            if kind == "optional":
                element_edge(tt, "optional")
                return
            if kind == "array":
                element_edge(tt, "array")
                return
            if kind == "var_array":
                element_edge(tt, "vec")
                return
            # opaque / string / primitives: no completeness edge
            return

        walk(t, "direct")
        return out

    def _build_graph(self):
        # nodes: struct/union names. edges: A -> B when B must be complete
        # inside A's definition.
        edges: dict[str, list[tuple[str, tuple, str]]] = {n: [] for n in {**self.structs, **self.unions}}

        def add(parent: str, member: tuple, t: dict):
            for target, kind in self._member_edges(t):
                edges[parent].append((target, member, kind))

        for name, d in self.structs.items():
            for i, f in enumerate(d.data["fields"]):
                add(name, ("field", i), f["type"])
        for name, d in self.unions.items():
            for i, a in enumerate(d.data["arms"]):
                if a.get("type"):
                    add(name, ("arm", i), a["type"])

        # Tarjan SCC
        index_of: dict[str, int] = {}
        low: dict[str, int] = {}
        on_stack: set[str] = set()
        stack: list[str] = []
        sccs: list[list[str]] = []
        counter = [0]

        def strongconnect(v: str):
            index_of[v] = low[v] = counter[0]
            counter[0] += 1
            stack.append(v)
            on_stack.add(v)
            for w, _, _ in edges.get(v, []):
                if w not in index_of:
                    strongconnect(w)
                    low[v] = min(low[v], low[w])
                elif w in on_stack:
                    low[v] = min(low[v], index_of[w])
            if low[v] == index_of[v]:
                scc = []
                while True:
                    w = stack.pop()
                    on_stack.discard(w)
                    scc.append(w)
                    if w == v:
                        break
                # a single-node SCC is cyclic only if it has a self-edge
                if len(scc) > 1 or any(w == v for w, _, _ in edges.get(v, [])):
                    sccs.append(scc)

        sys.setrecursionlimit(10000)
        for v in edges:
            if v not in index_of:
                strongconnect(v)

        in_scc = {n for scc in sccs for n in scc}
        # box every completeness edge whose endpoints share an SCC
        for parent, outs in edges.items():
            for target, member, kind in outs:
                if parent in in_scc and target in in_scc:
                    self.boxed_edges[(parent, *member)] = kind

        # topo order over remaining completeness edges
        order_edges: dict[str, set[str]] = {n: set() for n in edges}
        indeg: dict[str, int] = {n: 0 for n in edges}
        for parent, outs in edges.items():
            for target, member, kind in outs:
                if (parent, *member) in self.boxed_edges:
                    continue  # Box<> only needs a forward declaration
                if parent == target:
                    continue
                if parent not in order_edges[target]:
                    order_edges[target].add(parent)
                    indeg[parent] += 1
        ready = [n for n in edges if indeg[n] == 0]
        ready.sort(key=lambda n: self._decl_index(n))
        while ready:
            n = ready.pop(0)
            self.emit_order.append(n)
            for dependent in sorted(order_edges[n], key=lambda x: self._decl_index(x)):
                indeg[dependent] -= 1
                if indeg[dependent] == 0:
                    ready.append(dependent)
                    ready.sort(key=lambda x: self._decl_index(x))
        leftover = [n for n in edges if n not in self.emit_order]
        if leftover:
            raise RuntimeError(f"unresolved type cycle: {leftover}")

    def _decl_index(self, name: str) -> int:
        for i, d in enumerate(self.defs):
            if d.name == name:
                return i
        return 10**9

    # ----- metrics ----------------------------------------------------------

    def _member_min_size(self, t: dict, boxed: bool) -> int:
        kind = t["kind"]
        if boxed:
            # Box/OptionalBox encode like the underlying value/optional.
            if kind == "optional":
                return 4
            return self._member_min_size(t, False)
        if kind == "ref":
            d = self.by_name[t["name"]]
            if d.kind == "typedef":
                return self._member_min_size(d.data["type"], False)
            return self.min_size.get(t["name"], 0)
        if kind in ("int", "unsigned_int", "bool"):
            return 4
        if kind in ("hyper", "unsigned_hyper"):
            return 8
        if kind == "opaque_fixed":
            return pad4(t["size"])
        if kind in ("opaque_var", "string", "var_array"):
            return 4  # length prefix only
        if kind == "array":
            return t["count"] * self._member_min_size(t["element"], False)
        if kind == "optional":
            return 4  # presence flag only
        raise ValueError(kind)

    def _compute_min_sizes(self):
        for _ in range(len(self.defs) + 1):
            changed = False
            for name, d in {**self.structs, **self.unions}.items():
                if d.kind == "struct":
                    size = 0
                    for i, f in enumerate(d.data["fields"]):
                        size += self._member_min_size(f["type"], (name, "field", i) in self.boxed_edges)
                else:
                    best = None
                    for i, a in enumerate(d.data["arms"]):
                        if not a.get("type"):
                            arm = 0
                        else:
                            arm = self._member_min_size(a["type"], (name, "arm", i) in self.boxed_edges)
                        best = arm if best is None else min(best, arm)
                    size = 4 + (best or 0)
                if self.min_size.get(name) != size:
                    self.min_size[name] = size
                    changed = True
            if not changed:
                return
        raise RuntimeError("min size fixpoint did not converge")

    def _member_min_depth(self, t: dict, boxed: bool) -> int:
        kind = t["kind"]
        if boxed and kind == "optional":
            return 0
        if kind == "ref":
            d = self.by_name[t["name"]]
            if d.kind == "typedef":
                return self._member_min_depth(d.data["type"], boxed)
            return self.min_depth.get(t["name"], 0)
        if kind == "optional":
            return 0  # may be absent
        if kind in ("var_array", "opaque_var", "string"):
            return 0  # may be empty
        if kind == "array":
            return self._member_min_depth(t["element"], boxed)
        if kind == "opaque_fixed":
            return 0
        return 0  # primitives

    def _compute_min_depths(self):
        for _ in range(len(self.defs) + 1):
            changed = False
            for name, d in {**self.structs, **self.unions}.items():
                if d.kind == "struct":
                    depth = 0
                    for i, f in enumerate(d.data["fields"]):
                        boxed = (name, "field", i) in self.boxed_edges
                        depth = max(depth, 1 + self._member_min_depth(f["type"], boxed))
                else:
                    # a union can choose its shallowest arm
                    depth = min(
                        (1 + self._member_min_depth(a["type"], (name, "arm", i) in self.boxed_edges))
                        if a.get("type") else 0
                        for i, a in enumerate(d.data["arms"])
                    )
                if self.min_depth.get(name) != depth:
                    self.min_depth[name] = depth
                    changed = True
            if not changed:
                return
        raise RuntimeError("min depth fixpoint did not converge")

    # ----- emission ---------------------------------------------------------

    def emit(self) -> dict[pathlib.Path, str]:
        files: dict[pathlib.Path, str] = {}
        # one header/source pair per .x file
        members: dict[int, list[Def]] = {}
        for d in self.defs:
            members.setdefault(d.file_index, []).append(d)
        for file_index in sorted(members):
            stem = self._stem(file_index)
            files[OUT_HEADER_DIR / f"{stem}.hpp"] = self._emit_file_header(file_index, members[file_index])
            files[OUT_DIR / f"codec_{stem}.cpp"] = self._emit_cpp(members[file_index], file_index)
        files[OUT_HEADER] = self._emit_umbrella()
        files[OUT_DIR / "registry.cpp"] = self._emit_registry()
        return files

    def _file_names(self) -> list[str]:
        return self._ast_files

    def _stem(self, file_index: int) -> str:
        return pathlib.Path(self._file_names()[file_index]).stem.lower().replace("-", "_")

    def _refs_in_type(self, t: dict) -> set[str]:
        """Every 'ref' name appearing anywhere in a type node."""
        names: set[str] = set()

        def walk(tt: dict):
            if tt["kind"] == "ref":
                names.add(tt["name"])
                return
            for key in ("element",):
                if key in tt:
                    walk(tt[key])

        walk(t)
        return names

    def _file_deps(self) -> dict[int, set[int]]:
        """file_index -> file_index set whose headers must be included."""
        deps: dict[int, set[int]] = {}
        for d in self.defs:
            refs: set[str] = set()
            if d.kind in ("struct", "union"):
                if d.kind == "struct":
                    mems = d.data["fields"]
                else:
                    mems = [a for a in d.data["arms"] if a.get("type")]
                    if d.data["discriminant"]["type"]["kind"] == "ref":
                        refs.add(d.data["discriminant"]["type"]["name"])
                for m in mems:
                    refs |= self._refs_in_type(m["type"])
            elif d.kind == "typedef":
                refs = self._refs_in_type(d.data["type"])
            for r in refs:
                target = self.by_name.get(r)
                if target is not None and target.file_index != d.file_index:
                    deps.setdefault(d.file_index, set()).add(target.file_index)
        return deps

    def _emit_umbrella(self) -> str:
        # include file headers in topological order of the file graph
        deps = self._file_deps()
        order: list[int] = []
        done: set[int] = set()
        pending = set(range(len(self._file_names())))
        while pending:
            ready = sorted(f for f in pending if deps.get(f, set()) <= done)
            if not ready:
                raise RuntimeError("file dependency cycle")
            order.extend(ready)
            done.update(ready)
            pending -= set(ready)
        out = [BANNER, "#pragma once", ""]
        for f in order:
            out.append(f'#include "stellar/xdr/generated/{self._stem(f)}.hpp"')
        out.append("")
        return "\n".join(out)

    def _emit_file_header(self, file_index: int, members: list[Def]) -> str:
        deps = self._file_deps().get(file_index, set())
        out: list[str] = [BANNER, "#pragma once\n"]
        out.append('#include "stellar/xdr/bounded.hpp"')
        out.append('#include "stellar/xdr/box.hpp"')
        out.append('#include "stellar/xdr/codec.hpp"')
        for dep in sorted(deps):
            out.append(f'#include "stellar/xdr/generated/{self._stem(dep)}.hpp"')
        out.append("")
        out.append("#include <array>\n#include <compare>\n#include <cstdint>\n#include <optional>\n#include <string_view>\n#include <utility>\n#include <variant>\n")
        out.append("namespace stellar::inline v1::xdr {\n")

        own = [d for d in members if d.kind in ("struct", "union")]
        for d in own:
            kw = "class" if d.kind == "union" else "struct"
            out.append(f"{kw} {ident(d.name)};")
        out.append("")

        foreign = {n for i in deps for n in self._names_of_file(i)}
        emitted: set[str] = set()
        while True:
            progressed = False
            for d in members:
                if d.kind != "typedef" or d.name in emitted:
                    continue
                tdeps = self._typedef_dep_names(d.data["type"])
                if tdeps <= (emitted | set(self.by_name) - set(self.typedefs) | foreign):
                    out.append(self._emit_typedef(d))
                    emitted.add(d.name)
                    progressed = True
            if not progressed:
                break
        remaining = [d.name for d in members if d.kind == "typedef" and d.name not in emitted]
        if remaining:
            raise RuntimeError(f"typedef cycle in {self._file_names()[file_index]}: {remaining}")
        out.append("")

        for d in members:
            if d.kind == "enum":
                out.append(self._emit_enum(d))
        out.append("")

        for name in self.emit_order:
            d = self.by_name[name]
            if d.file_index == file_index:
                out.append(self._emit_struct(d) if d.kind == "struct" else self._emit_union(d))

        for d in members:
            if d.kind == "const":
                out.append(f"inline constexpr std::int64_t {ident(d.name)} = {d.data['value']};")
        out.append("")
        out.append("// --- Codec<T> specializations ---")
        for d in members:
            if d.kind in ("enum", "struct", "union"):
                out += self._codec_decl(d)
        out.append("")
        out.append("}  // namespace stellar::inline v1::xdr\n")
        return "\n".join(out)

    def _names_of_file(self, file_index: int) -> set[str]:
        return {d.name for d in self.defs if d.file_index == file_index}

    def _typedef_dep_names(self, t: dict) -> set[str]:
        out: set[str] = set()

        def walk(tt):
            k = tt["kind"]
            if k == "ref" and tt["name"] in self.typedefs:
                out.add(tt["name"])
                walk(self.typedefs[tt["name"]].data["type"])
            for key in ("element",):
                if key in tt:
                    walk(tt[key])

        walk(t)
        return out

    def _emit_typedef(self, d: Def) -> str:
        return f"using {ident(d.name)} = {self.cpp_type(d.data['type'])};"

    def _emit_enum(self, d: Def) -> str:
        lines: list[str] = []
        if d.data.get("source"):
            for ln in d.data["source"].splitlines():
                lines.append(f"/// {ln}" if ln.strip() else "///")
        lines.append(f"enum class {ident(d.name)} : std::int32_t {{")
        for m in d.data["members"]:
            lines.append(f"  {ident(m['name'])} = {m['value']},")
        lines.append("};")
        lines.append(f"const char* enum_name({ident(d.name)}) noexcept;")
        lines.append(f"bool enum_from_name(std::string_view, {ident(d.name)}&) noexcept;")
        return "\n".join(lines)

    def _emit_struct(self, d: Def) -> str:
        name = ident(d.name)
        lines: list[str] = []
        if d.data.get("source"):
            for ln in d.data["source"].splitlines():
                lines.append(f"/// {ln}" if ln.strip() else "///")
        lines.append(f"struct {name} {{")
        for i, f in enumerate(d.data["fields"]):
            t = self.boxed_cpp_type(f["type"], (d.name, "field", i))
            lines.append(f"  {t} {ident(f['name'])};")
        lines.append(f"  bool operator==(const {name}&) const = default;")
        lines.append("};")
        return "\n".join(lines)

    def _emit_union(self, d: Def) -> str:
        name = ident(d.name)
        disc = d.data["discriminant"]
        disc_name = ident(disc["name"])
        disc_type_node = disc["type"]
        enum_disc = disc_type_node["kind"] == "ref" and disc_type_node["name"] in self.enums
        disc_cpp = ident(disc_type_node["name"]) if enum_disc else "std::int32_t"

        arms = d.data["arms"]
        alt_types: list[str] = []
        accessor_names: dict[int, str] = {}
        for i, a in enumerate(arms):
            if a.get("type"):
                t = self.boxed_cpp_type(a["type"], (d.name, "arm", i))
                alt_types.append(t)
                if a.get("name"):
                    accessor_names[i] = ident(a["name"])
            else:
                alt_types.append("std::monostate")

        # reserved public names: discriminant accessor and framework members
        reserved = {disc_name, "arm_index", "variant", "index", "type"}
        for i, an in accessor_names.items():
            if an in reserved:
                accessor_names[i] = an + "_arm"

        first_case = arms[0]["cases"][0]
        first_disc = ident(first_case["name"]) if "name" in first_case else str(first_case["value"])

        lines: list[str] = []
        if d.data.get("source"):
            for ln in d.data["source"].splitlines():
                lines.append(f"/// {ln}" if ln.strip() else "///")
        lines.append(f"class {name} {{")
        lines.append(" public:")
        if enum_disc:
            lines.append(f"  using discriminant_type = {disc_cpp};")
        else:
            lines.append("  using discriminant_type = std::int32_t;")
        lines.append(f"  {name}() = default;")
        lines.append(f"  [[nodiscard]] {disc_cpp} {disc_name}() const noexcept {{ return t_; }}")
        lines.append("  [[nodiscard]] std::size_t arm_index() const noexcept { return v_.index(); }")

        # factories: one per case
        for i, a in enumerate(arms):
            for c in a["cases"]:
                if "name" in c:
                    fname = camelize(c["name"])
                    disc_ref = f"{disc_cpp}::{ident(c['name'])}" if enum_disc else str(c["value"])
                else:
                    fname = f"v{c['value']}"
                    disc_ref = str(c["value"])
                if a.get("type"):
                    at = alt_types[i]
                    lines.append(
                        f"  static {name} {fname}(const {at}& v) {{ {name} r; r.t_ = {disc_ref}; "
                        f"r.v_.template emplace<{i}>(v); return r; }}"
                    )
                    lines.append(
                        f"  static {name} {fname}({at}&& v) {{ {name} r; r.t_ = {disc_ref}; "
                        f"r.v_.template emplace<{i}>(std::move(v)); return r; }}"
                    )
                else:
                    lines.append(
                        f"  static {name} {fname}() {{ {name} r; r.t_ = {disc_ref}; "
                        f"r.v_.template emplace<{i}>(); return r; }}"
                    )

        # accessors: one per named non-void arm
        for i, an in accessor_names.items():
            at = alt_types[i]
            lines.append(f"  [[nodiscard]] {at}& {an}() {{ return std::get<{i}>(v_); }}")
            lines.append(f"  [[nodiscard]] const {at}& {an}() const {{ return std::get<{i}>(v_); }}")
            lines.append(f"  [[nodiscard]] {at}* get_if_{an}() noexcept {{ return std::get_if<{i}>(&v_); }}")
            lines.append(f"  [[nodiscard]] const {at}* get_if_{an}() const noexcept {{ return std::get_if<{i}>(&v_); }}")

        lines.append(f"  bool operator==(const {name}&) const = default;")
        lines.append("")
        lines.append(" private:")
        variant = ", ".join(alt_types)
        lines.append(f"  std::variant<{variant}> v_;")
        if enum_disc:
            lines.append(f"  {disc_cpp} t_ = {disc_cpp}::{first_disc};")
        else:
            lines.append(f"  std::int32_t t_ = {first_disc};")
        lines.append("")
        lines.append("  template <typename> friend struct Codec;")
        lines.append("};")
        return "\n".join(lines)

    # ----- .cpp emission ----------------------------------------------------

    def _codec_decl(self, d: Def) -> list[str]:
        name = ident(d.name)
        visit = self._visit_body(d)
        return [
            "template <>",
            f"struct Codec<{name}> {{",
            f"  static constexpr std::uint64_t kMinSize = {self.min_size.get(d.name, 4)};",
            f"  static bool encode(const {name}&, Encoder&);",
            f"  static bool decode({name}&, Decoder&);",
            f"  static bool gen({name}&, XdrRng&, std::uint32_t);",
            "  template <typename F>",
            f"  static void visit_fields(const {name}& v, F&& f) {{",
            *visit,
            "  }",
            "};",
        ]

    def _visit_body(self, d: Def) -> list[str]:
        """Body of Codec<T>::visit_fields, emitted inline in the header."""
        if d.kind == "enum":
            return [f"    f(enum_name(v), v);"]
        if d.kind == "struct":
            return [f'    f("{f_["name"]}", v.{ident(f_["name"])});' for f_ in d.data["fields"]]
        # union: discriminant then a switch on the typed arm payload
        disc = d.data["discriminant"]
        enum_disc = disc["type"]["kind"] == "ref" and disc["type"]["name"] in self.enums
        disc_cpp = ident(disc["type"]["name"]) if enum_disc else "std::int32_t"
        lines = [f'    f("{disc["name"]}", v.t_);', "    switch (v.t_) {"]
        for i, a in enumerate(d.data["arms"]):
            if not a.get("type"):
                continue
            for c in a["cases"]:
                label = f"{disc_cpp}::{ident(c['name'])}" if "name" in c else str(c["value"])
                lines.append(f"      case {label}:")
            an = a.get("name") or "value"
            lines.append(f'        f("{an}", std::get<{i}>(v.v_));')
            lines.append("        return;")
        lines.append("      default: return;")
        lines.append("    }")
        return lines

    def _emit_cpp(self, members: list[Def], file_index: int) -> str:
        out = [BANNER, '#include "stellar/xdr/generated/types.hpp"\n']
        out.append("namespace stellar::inline v1::xdr {\n")

        # codecs for typedefs: resolve to the emitted specialization of the
        # underlying type — no per-alias codec needed; the registry aliases them.
        # Emit Codec only for typedefs whose resolved type is a container alias
        # (BoundedVector etc.) — the Codec partial spec covers the alias since
        # `using` makes it the same type. So typedefs emit nothing here.

        for d in members:
            if d.kind == "enum":
                out += self._emit_enum_impl(d)
            elif d.kind == "struct":
                out += self._emit_struct_impl(d)
            elif d.kind == "union":
                out += self._emit_union_impl(d)

        out.append("}  // namespace stellar::inline v1::xdr\n")
        return "\n".join(out)

    def _emit_enum_impl(self, d: Def) -> list[str]:
        n = ident(d.name)
        lines: list[str] = []
        lines.append(f"const char* enum_name({n} v) noexcept {{")
        lines.append("  switch (v) {")
        for m in d.data["members"]:
            lines.append(f"    case {n}::{ident(m['name'])}: return \"{m['name']}\";")
        lines.append("    default: return nullptr;")
        lines.append("  }")
        lines.append("}")
        lines.append(f"bool enum_from_name(std::string_view s, {n}& v) noexcept {{")
        for m in d.data["members"]:
            lines.append(f"  if (s == \"{m['name']}\") {{ v = {n}::{ident(m['name'])}; return true; }}")
        lines.append("  return false;")
        lines.append("}")
        lines.append("")
        lines.append(f"bool Codec<{n}>::encode(const {n}& v, Encoder& e) {{")
        lines.append("  switch (v) {")
        for m in d.data["members"]:
            lines.append(f"    case {n}::{ident(m['name'])}:")
        lines.append("      break;")
        lines.append("    default: return e.fail(stellar::v1::ErrorCode::kEncodeFailed, \"unknown enum value\");")
        lines.append("  }")
        lines.append("  return e.i32(static_cast<std::int32_t>(v));")
        lines.append("}")
        lines.append(f"bool Codec<{n}>::decode({n}& v, Decoder& d) {{")
        lines.append("  std::int32_t x;")
        lines.append("  if (!d.i32(x)) return false;")
        lines.append("  switch (x) {")
        for m in d.data["members"]:
            lines.append(f"    case {m['value']}: v = {n}::{ident(m['name'])}; return true;")
        lines.append("    default: return d.fail(stellar::v1::ErrorCode::kDecodeFailed, \"unknown enum value\");")
        lines.append("  }")
        lines.append("}")
        lines.append(f"bool Codec<{n}>::gen({n}& v, XdrRng& r, std::uint32_t) {{")
        members = d.data["members"]
        lines.append(f"  switch (r.index({len(members)})) {{")
        for i, m in enumerate(members):
            lines.append(f"    case {i}: v = {n}::{ident(m['name'])}; return true;")
        lines.append("  }")
        lines.append(f"  v = {n}::{ident(members[0]['name'])};")
        lines.append("  return true;")
        lines.append("}")
        lines.append("")
        return lines

    def _emit_struct_impl(self, d: Def) -> list[str]:
        n = ident(d.name)
        lines: list[str] = []
        enc_fields = " &&\n      ".join(
            f"e.field(\"{f['name']}\", v.{ident(f['name'])})" for f in d.data["fields"]
        ) or "true"
        dec_fields = " &&\n      ".join(
            f"d.field(\"{f['name']}\", v.{ident(f['name'])})" for f in d.data["fields"]
        ) or "true"
        lines.append(f"bool Codec<{n}>::encode(const {n}& v, Encoder& e) {{")
        lines.append(f"  return {enc_fields};")
        lines.append("}")
        lines.append(f"bool Codec<{n}>::decode({n}& v, Decoder& d) {{")
        lines.append("  Decoder::DepthGuard g(d);")
        lines.append("  if (!g) return false;")
        lines.append(f"  return {dec_fields};")
        lines.append("}")
        lines.append(f"bool Codec<{n}>::gen({n}& v, XdrRng& r, std::uint32_t depth) {{")
        for f in d.data["fields"]:
            lines.append(f"  if (!Codec<decltype(v.{ident(f['name'])})>::gen(v.{ident(f['name'])}, r, depth)) return false;")
        lines.append("  return true;")
        lines.append("}")
        lines.append("")
        return lines

    def _emit_union_impl(self, d: Def) -> list[str]:
        n = ident(d.name)
        disc = d.data["discriminant"]
        enum_disc = disc["type"]["kind"] == "ref" and disc["type"]["name"] in self.enums
        disc_cpp = ident(disc["type"]["name"]) if enum_disc else "std::int32_t"
        arms = d.data["arms"]
        lines: list[str] = []

        # encode
        lines.append(f"bool Codec<{n}>::encode(const {n}& v, Encoder& e) {{")
        lines.append("  switch (v.t_) {")
        for i, a in enumerate(arms):
            for c in a["cases"]:
                label = f"{disc_cpp}::{ident(c['name'])}" if "name" in c else str(c["value"])
                lines.append(f"    case {label}:")
            if a.get("type"):
                lines.append(
                    f"      if (const auto* p = std::get_if<{i}>(&v.v_)) {{"
                    f" return e.i32(static_cast<std::int32_t>(v.t_)) && "
                    f"Codec<std::remove_cvref_t<decltype(*p)>>::encode(*p, e); }}"
                )
                lines.append(f"      return e.fail(stellar::v1::ErrorCode::kEncodeFailed, \"{n}: payload does not match discriminant\");")
            else:
                lines.append("      return e.i32(static_cast<std::int32_t>(v.t_));")
        lines.append(f"    default: return e.fail(stellar::v1::ErrorCode::kEncodeFailed, \"{n}: unknown discriminant\");")
        lines.append("  }")
        lines.append("}")
        lines.append("")

        # decode
        lines.append(f"bool Codec<{n}>::decode({n}& v, Decoder& d) {{")
        lines.append("  Decoder::DepthGuard g(d);")
        lines.append("  if (!g) return false;")
        lines.append("  std::int32_t tag;")
        lines.append("  if (!d.i32(tag)) return false;")
        lines.append("  switch (tag) {")
        for i, a in enumerate(arms):
            for c in a["cases"]:
                lines.append(f"    case {c['value']}:")
            if a.get("type"):
                an = a.get("name") or "value"
                lines.append(f"      v.t_ = static_cast<{disc_cpp}>(tag);")
                lines.append(f"      v.v_.template emplace<{i}>();")
                lines.append(f"      return d.field(\"{an}\", std::get<{i}>(v.v_));")
            else:
                lines.append(f"      v.t_ = static_cast<{disc_cpp}>(tag);")
                lines.append(f"      v.v_.template emplace<{i}>();")
                lines.append("      return true;")
        lines.append(f"    default: return d.fail(stellar::v1::ErrorCode::kDecodeFailed, \"{n}: unknown discriminant\");")
        lines.append("  }")
        lines.append("}")
        lines.append("")

        # gen
        lines.append(f"bool Codec<{n}>::gen({n}& v, XdrRng& r, std::uint32_t depth) {{")
        # min-depth per arm (payload min depth + 1)
        arm_depths = []
        for i, a in enumerate(arms):
            if a.get("type"):
                boxed = (d.name, "arm", i) in self.boxed_edges
                arm_depths.append(self._member_min_depth(a["type"], boxed))
            else:
                arm_depths.append(0)
        best = min(range(len(arms)), key=lambda i: arm_depths[i])
        lines.append(f"  std::size_t i = depth >= 4 ? {best} : r.index({len(arms)});")
        lines.append("  switch (i) {")
        for i, a in enumerate(arms):
            lines.append(f"    case {i}: {{")
            if a.get("type"):
                c0 = a["cases"][0]
                disc_expr = f"{disc_cpp}::{ident(c0['name'])}" if "name" in c0 else str(c0["value"])
                lines.append(f"      v.t_ = {disc_expr};")
                lines.append(f"      auto& p = v.v_.template emplace<{i}>();")
                lines.append(f"      return Codec<std::remove_reference_t<decltype(p)>>::gen(p, r, depth + 1);")
            else:
                c0 = a["cases"][0]
                disc_expr = f"{disc_cpp}::{ident(c0['name'])}" if "name" in c0 else str(c0["value"])
                lines.append(f"      v.t_ = {disc_expr};")
                lines.append(f"      v.v_.template emplace<{i}>();")
                lines.append("      return true;")
            lines.append("    }")
        lines.append("  }")
        lines.append("  return false;")
        lines.append("}")
        lines.append("")
        return lines

    # ----- registry ---------------------------------------------------------

    def _emit_registry(self) -> str:
        out = [BANNER, '#include "stellar/xdr/generated/types.hpp"\n']
        out.append("namespace stellar::inline v1::xdr {\n")
        out.append("namespace {\n")
        out.append("template <typename T>")
        out.append("bool validate_impl(ByteSpan data) { return decode<T>(data).ok(); }")
        out.append("")
        out.append("template <typename T>")
        out.append("Result<Bytes> reencode_impl(ByteSpan data) {")
        out.append("  auto r = decode<T>(data);")
        out.append("  if (!r.ok()) return r.error();")
        out.append("  return encode(*r);")
        out.append("}")
        out.append("")
        out.append("template <typename T>")
        out.append("Result<Bytes> make_random_impl(std::uint64_t* seed, std::uint32_t depth) {")
        out.append("  XdrRng rng(*seed);")
        out.append("  T v;")
        out.append("  if (!Codec<T>::gen(v, rng, depth))")
        out.append("    return stellar::v1::Error{stellar::v1::ErrorCode::kInternal, \"failed to generate value\"};")
        out.append("  *seed = rng.state;")
        out.append("  return encode(v);")
        out.append("}")
        out.append("")
        out.append("template <typename T>")
        out.append("Result<void> visit_impl(ByteSpan data, void* ctx, void (*cb)(void*, const char*)) {")
        out.append("  auto r = decode<T>(data);")
        out.append("  if (!r.ok()) return r.error();")
        out.append("  visit_fields(*r, [&](std::string_view n, const auto&) { cb(ctx, n.data()); });")
        out.append("  return {};")
        out.append("}")
        out.append("")
        # one entry per declared name (typedefs resolve to underlying impl)
        entries: list[tuple[str, str]] = []
        for d in self.defs:
            if d.kind == "typedef":
                resolved = self.resolve_ref(d.name)
                if resolved is None:
                    continue
                target = resolved.name
                if resolved.kind == "typedef":
                    # typedef of a container/primitive: use the aliased C++ type name
                    target = d.name
                entries.append((d.name, d.name))
            elif d.kind == "const":
                continue
            else:
                entries.append((d.name, d.name))
        out.append("constexpr TypeEntry kEntries[] = {")
        for entry_name, cpp in entries:
            out.append(
                f"    {{\"{entry_name}\", &validate_impl<{ident(cpp)}>, &reencode_impl<{ident(cpp)}>,"
                f" &make_random_impl<{ident(cpp)}>, &visit_impl<{ident(cpp)}>}},"
            )
        out.append("};")
        out.append("}  // namespace\n")
        out.append("const TypeEntry* find_type(std::string_view name) noexcept {")
        out.append("  for (const auto& e : kEntries)")
        out.append("    if (name == e.name) return &e;")
        out.append("  return nullptr;")
        out.append("}")
        out.append("")
        out.append("std::span<const TypeEntry> all_types() noexcept { return kEntries; }")
        out.append("")
        out.append("}  // namespace stellar::inline v1::xdr\n")
        return "\n".join(out)

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = parser.parse_args()

    ast = json.loads(XDR_JSON.read_text())
    gen = Gen(ast)
    gen._ast_files = [f["name"] for f in ast["files"]]

    files = gen.emit()
    # stale generated headers from older generator versions must not linger
    stale = sorted(
        [p for p in OUT_HEADER_DIR.glob("*.hpp") if p.name != "types.hpp" and p not in files]
        + [p for p in OUT_DIR.glob("*.cpp") if p not in files]
    )

    if args.check:
        drift = [p for p in stale]
        for path, content in sorted(files.items()):
            if not path.exists() or path.read_text() != content:
                drift.append(path)
        if drift:
            for p in drift:
                print(f"drift: {p.relative_to(ROOT)}", file=sys.stderr)
            print("run tools/xdrgen/generate.py to regenerate", file=sys.stderr)
            return 1
        print(f"ok: {len(files)} generated files are up to date")
        return 0

    for path in stale:
        path.unlink()
        print(f"removed stale {path.relative_to(ROOT)}")
    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        old = path.read_text() if path.exists() else None
        if old == content:
            continue
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)} ({len(content)} bytes)")
    print(f"done: {len(ast['definitions'])} definitions -> {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
