#!/usr/bin/env python3
"""Generate compatibility/rpc.md from the OpenRPC spec + test coverage.

Reads stellar-docs/static/stellar-rpc.openrpc.json (vendored or fetched),
emits a per-method conformance table: implemented? covered by mock/live/e2e?

Usage:
  python3 tools/compat/gen_rpc_conformance.py [path/to/openrpc.json]

If no spec is given, uses the built-in method list so the table always
produces — the generated file is checked in so reviewers see coverage drift.
"""
import json
import os
import sys

# method -> (implemented, mock test, live test, e2e)
# e2e = exercised by the end-to-end contract invoke on testnet
COVERAGE = {
    "getHealth":          (True,  True,  True,  False),
    "getVersionInfo":     (True,  False, True,  False),
    "getNetwork":         (True,  False, True,  False),
    "getFeeStats":        (True,  False, True,  False),
    "getLatestLedger":    (True,  False, True,  False),
    "getLedgers":         (True,  False, True,  False),
    "getLedgerEntries":   (True,  True,  False, True),
    "getTransaction":     (True,  True,  False, False),
    "getTransactions":    (True,  True,  False, False),
    "getEvents":          (True,  True,  False, False),
    "queryEvents":        (True,  True,  False, False),
    "sendTransaction":    (True,  True,  False, True),
    "simulateTransaction":(True,  True,  False, True),
}

NOTE = """## Deployment schema variants handled

- `getLedgerEntries` key field: `keyXdr` (legacy) or `key` (newer).
- `getLedgerEntries` value: `xdr` may be `LedgerEntry` or bare `LedgerEntryData`.
- `getLedgerEntries` entry: lazy decode — `raw_xdr`/`decode_error` fields surface
  one bad arm after a protocol upgrade instead of sinking the whole response.
- `getFeeStats` buckets: numeric strings; fields `min/mode/p10/p50/p90/p95/p99/max`.
- `simulateTransaction`: envelope (not raw tx) in `transaction`; response fields
  `transactionData`/`events`/`results[].xdr`/`results[].auth` (legacy
  `transactionDataXdr`/`eventsXdr`/`authXdr` also accepted).
- Soroban `resourceFee` padded ~25% vs sim estimate for submission.
- `sendTransaction`: `TRY_AGAIN_LATER` re-sends with linear backoff;
  `DUPLICATE` returns a distinct status.
"""


def load_methods(spec_path):
    if spec_path and os.path.exists(spec_path):
        with open(spec_path) as f:
            spec = json.load(f)
        return [m["name"] for m in spec.get("methods", [])]
    return sorted(COVERAGE)


def main():
    spec_path = sys.argv[1] if len(sys.argv) > 1 else None
    methods = load_methods(spec_path)
    missing = [m for m in methods if m not in COVERAGE]
    for m in missing:
        COVERAGE[m] = (False, False, False, False)

    out = ["# Stellar RPC conformance", "",
           "Generated by `tools/compat/gen_rpc_conformance.py`. `mock` = unit",
           "test against canned responses, `live` = `RpcLive.*` against a real",
           "endpoint (skips without `STELLAR_RPC_ENDPOINT`), `e2e` = end-to-end",
           "contract invoke on testnet.", "",
           "| Method | Implemented | Mock | Live | e2e |",
           "|---|---|---|---|---|"]
    for m in methods:
        impl, mock, live, e2e = COVERAGE[m]
        out.append(f"| {m} | {'Y' if impl else '—'} | "
                   f"{'Y' if mock else '—'} | {'Y' if live else '—'} | "
                   f"{'Y' if e2e else '—'} |")
    n = sum(1 for m in methods if COVERAGE[m][0])
    out += ["", f"Coverage: {n}/{len(methods)} methods implemented.",
            "", NOTE]
    dest = os.path.join(os.path.dirname(__file__), "..", "..", "compatibility", "rpc.md")
    with open(os.path.normpath(dest), "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.normpath(dest)} ({n}/{len(methods)} methods)")


if __name__ == "__main__":
    main()
